void ADVGameMode::Radio(const FString& Speaker, const FString& Text, float Delay)
{
	ADVGameState* GS = GetDVGameState();
	if (!GS)
	{
		return;
	}
	if (Delay <= 0.f)
	{
		GS->MulticastRadio(Speaker, Text);
		return;
	}
	FTimerHandle Handle;
	GetWorldTimerManager().SetTimer(Handle, FTimerDelegate::CreateWeakLambda(GS, [GS, Speaker, Text]() { GS->MulticastRadio(Speaker, Text); }), Delay, false);
}

void ADVGameMode::RequestOrbitalStrike(APlayerController* Caller, const FVector& Target)
{
	ADVGameState* GS = GetDVGameState();
	const float Now = GetWorld()->GetTimeSeconds();
	if (!GS || bMissionEnded || bIsHub || !Caller || Now < GS->OrbitalReadyTime)
	{
		return;
	}
	APawn* CallerPawn = Caller->GetPawn();
	if (!CallerPawn || FVector::Dist(CallerPawn->GetActorLocation(), Target) > 20000.f)
	{
		return;	// out of designator range (also guards against spoofed targets)
	}
	const ADVSoldierCharacter* Commander = Cast<ADVSoldierCharacter>(Caller->GetPawn());
	const float Favour = Commander && Commander->GetCommanderLevel() >= DVPerks::KestrelFavour ? 0.75f : 1.f;
	GS->OrbitalReadyTime = Now + OrbitalCooldown * Favour + OrbitalDelay;
	GS->MulticastOrbitalStrike(Target, OrbitalDelay);
	Radio(TEXT("Capt. Vance (Kestrel)"), TEXT("Target painted. Rounds away, three seconds. Danger close!"));

	FTimerHandle Handle;
	GetWorldTimerManager().SetTimer(Handle, FTimerDelegate::CreateUObject(this, &ADVGameMode::ResolveOrbitalStrike,
		TWeakObjectPtr<APawn>(CallerPawn), Target), OrbitalDelay, false);
}

void ADVGameMode::ResolveOrbitalStrike(TWeakObjectPtr<APawn> Caller, FVector Target)
{
	// Friendly fire is on for orbital strikes: that's what "danger close" means.
	ADVSoldierCharacter* Shooter = Cast<ADVSoldierCharacter>(Caller.Get());
	if (!Shooter)
	{
		if (const APawn* Vehicle = Caller.Get())
		{
			if (const UDVSeatComponent* Seat = Vehicle->FindComponentByClass<UDVSeatComponent>())
			{
				Shooter = Seat->Driver;
			}
		}
	}
	DVCombat::RadialDamage(Shooter, Target, OrbitalRadius, OrbitalDamage, true);
}

void ADVGameMode::SetupOperation()
{
	ADVGameState* GS = GetDVGameState();
	if (!GS || bIsHub || bIsTrainingMap || GS->EnemiesTotal == 0)
	{
		return;	// Boot Camp and the hangar keep the simple rules
	}
	// The target sits at the heart of the garrison: the hostile closest to their centre of mass.
	FVector Centre = FVector::ZeroVector;
	TArray<FVector> Positions;
	for (TActorIterator<ADVSoldierCharacter> It(GetWorld()); It; ++It)
	{
		if (It->TeamId != PlayerTeamId)
		{
			Positions.Add(It->GetActorLocation());
			Centre += It->GetActorLocation();
		}
	}
	Centre /= FMath::Max(1, Positions.Num());
	FVector Target = Centre;
	float Best = TNumericLimits<float>::Max();
	for (const FVector& P : Positions)
	{
		if (FVector::DistSquared(P, Centre) < Best)
		{
			Best = FVector::DistSquared(P, Centre);
			Target = P;
		}
	}
	FHitResult Hit;
	if (GetWorld()->LineTraceSingleByChannel(Hit, Target + FVector(0.f, 0.f, 200.f), Target - FVector(0.f, 0.f, 2000.f), ECC_Visibility))
	{
		Target = Hit.ImpactPoint;
	}
	// The landing zone is behind the drop point: after the charges blow, the squad turns around and runs for it.
	FVector LZ = Target;
	for (TActorIterator<APlayerStart> It(GetWorld()); It; ++It)
	{
		const FVector Back = It->GetActorLocation() - It->GetActorForwardVector().GetSafeNormal2D() * 1600.f;
		LZ = Back - FVector(0.f, 0.f, 90.f);
		if (GetWorld()->LineTraceSingleByChannel(Hit, Back + FVector(0.f, 0.f, 1500.f), Back - FVector(0.f, 0.f, 3000.f), ECC_Visibility))
		{
			LZ = Hit.ImpactPoint;
		}
		break;
	}
	GS->bMultiStage = true;
	GS->Stage = EDVMissionStage::Clear;
	GS->ObjectiveLocation = Target;
	GS->ExtractLocation = LZ;

	// Hand-authored operations place their objectives in the map instead.
	FVector Obj1 = FVector::ZeroVector;
	for (TActorIterator<AActor> It(GetWorld()); It; ++It)
	{
		if (It->ActorHasTag(TEXT("DV_Obj_1"))) { Obj1 = It->GetActorLocation(); bScriptedObjectives = true; }
		if (It->ActorHasTag(TEXT("DV_Obj_2"))) { SecondObjective = It->GetActorLocation(); }
		if (It->ActorHasTag(TEXT("DV_LZ"))) { GS->ExtractLocation = It->GetActorLocation(); }
	}
	if (bScriptedObjectives)
	{
		// Straight to the first job; nobody waits for the whole garrison to fall.
		GS->ObjectiveLocation = Obj1;
		GS->Stage = EDVMissionStage::Sabotage;
		GS->ObjectiveText = TEXT("Destroy the air-defence controller");
		TargetNoun = TEXT("the air-defence controller");
	}

	const FString Map = GetWorld()->GetMapName();
	struct FNoun { const TCHAR* Key; const TCHAR* Noun; };
	static const FNoun Nouns[] = {
		{ TEXT("Europa"), TEXT("the drill head") }, { TEXT("Io"), TEXT("the forge core") }, { TEXT("Proxima"), TEXT("the jammer") },
		{ TEXT("Ceres"), TEXT("the signal mast") }, { TEXT("Gaia"), TEXT("the uplink") }, { TEXT("Outpost"), TEXT("the relay") } };
	TargetNoun = TEXT("the target");
	for (const FNoun& N : Nouns)
	{
		if (Map.Contains(N.Key))
		{
			TargetNoun = N.Noun;
			break;
		}
	}

	FActorSpawnParameters Params;
	Params.SpawnCollisionHandlingOverride = ESpawnActorCollisionHandlingMethod::AlwaysSpawn;
	GetWorld()->SpawnActor<ADVObjectiveBeacon>(ADVObjectiveBeacon::StaticClass(), Target, FRotator::ZeroRotator, Params);
	if (ADVObjectiveBeacon* Pad = GetWorld()->SpawnActor<ADVObjectiveBeacon>(ADVObjectiveBeacon::StaticClass(), LZ, FRotator::ZeroRotator, Params))
	{
		Pad->bExtraction = true;
	}
	GetWorldTimerManager().SetTimer(StageTimer, this, &ADVGameMode::TickStage, 0.25f, true);
}

void ADVGameMode::DevAdvanceStage()
{
#if !UE_BUILD_SHIPPING
	ADVGameState* GS = GetDVGameState();
	if (!GS || !GS->bMultiStage || bMissionEnded)
	{
		return;
	}
	switch (GS->Stage)
	{
	case EDVMissionStage::Clear: StartSabotage(); break;
	case EDVMissionStage::Sabotage: if (bScriptedObjectives) { StartCapture(); } else { StartDefend(); } break;
	case EDVMissionStage::Capture: StartDefend(); break;
	case EDVMissionStage::Defend: StartExtract(); break;
	default: break;
	}
#endif
}

bool ADVGameMode::AnyPlayerNear(const FVector& Location, float Radius) const
{
	for (FConstPlayerControllerIterator It = GetWorld()->GetPlayerControllerIterator(); It; ++It)
	{
		const APawn* P = It->Get() ? It->Get()->GetPawn() : nullptr;
		const ADVSoldierCharacter* S = Cast<ADVSoldierCharacter>(P);
		if (P && !(S && S->IsDead()) && FVector::Dist2D(P->GetActorLocation(), Location) <= Radius
			&& FMath::Abs(P->GetActorLocation().Z - Location.Z) < 600.f)
		{
			return true;
		}
	}
	return false;
}

void ADVGameMode::StartSabotage()
{
	ADVGameState* GS = GetDVGameState();
	GS->Stage = EDVMissionStage::Sabotage;
	GS->StageProgress = 0.f;
	GS->ObjectiveText = FString::Printf(TEXT("Plant demolition charges on %s"), *TargetNoun);
	StageStartTime = GetWorld()->GetTimeSeconds();
	Radio(TEXT("Gny. Sgt. Halloran"), FString::Printf(TEXT("Area's clear! Get to %s and plant the charges. Move!"), *TargetNoun), 1.5f);
}

void ADVGameMode::StartDefend()
{
	ADVGameState* GS = GetDVGameState();
	GS->Stage = EDVMissionStage::Defend;
	GS->StageProgress = 0.f;
	StageStartTime = GetWorld()->GetTimeSeconds();
	GS->StageEndTime = StageStartTime + HoldSeconds;
	GS->ObjectiveText = bScriptedObjectives ? TEXT("Hold the docks while the transports get clear") : TEXT("Hold until the charges blow");
	WavesSpawned = 0;
	Radio(TEXT("Gny. Sgt. Halloran"), bScriptedObjectives ? TEXT("Key's in! Locks are opening. Hold the docks till those ships are clear!")
		: TEXT("Charges set! Forty-five seconds. Dig in, they'll want it back."));
	GS->MulticastSound(TEXT("SW_Alarm"), GS->ObjectiveLocation, 0.6f, 1);
	Radio(TEXT("CINDER"), TEXT("YOU HAVE TOUCHED SOMETHING OF MINE."), 5.f);
}

void ADVGameMode::StartCapture()
{
	ADVGameState* GS = GetDVGameState();
	// The air defence goes up with the charges, and the sky opens for the Kestrel's aircraft.
	DVFx::Explosion(GetWorld(), GS->ObjectiveLocation, 1.2f);
	DVCombat::RadialDamage(SquadLeader.Get(), GS->ObjectiveLocation, 1400.f, 500.f, false);
	GS->Stage = EDVMissionStage::Capture;
	GS->StageProgress = 0.f;
	GS->ObjectiveLocation = SecondObjective;
	GS->ObjectiveText = TEXT("Take the dock control key across the harbour");
	StageStartTime = GetWorld()->GetTimeSeconds();
	Radio(TEXT("Capt. Vance (Kestrel)"), TEXT("Air defence is down! Ravens are cleared to approach. Now get me that dock key."), 1.f);
	Radio(TEXT("Gny. Sgt. Halloran"), TEXT("Bridge is blocked. Take the Marlin across the harbour, it's faster than walking round."), 6.f);
}

void ADVGameMode::StartExtract()
{
	ADVGameState* GS = GetDVGameState();
	if (!bScriptedObjectives)
	{
		DVFx::Explosion(GetWorld(), GS->ObjectiveLocation, 1.2f);
		DVCombat::RadialDamage(SquadLeader.Get(), GS->ObjectiveLocation, 1400.f, 500.f, false);	// the squad's charges: credit the leader
	}
	GS->Stage = EDVMissionStage::Extract;
	GS->StageProgress = 0.f;
	GS->ObjectiveText = TEXT("Get to the landing zone for extraction");
	StageStartTime = GetWorld()->GetTimeSeconds();
	Radio(TEXT("Capt. Vance (Kestrel)"), bScriptedObjectives ? FString(TEXT("Transports are in open water. Twelve thousand people, Delta. Raven Two-One is coming for you."))
		: FString::Printf(TEXT("Good kill on %s, Delta. Raven Two-One is inbound to your LZ. Get out of there."), *TargetNoun), 1.f);
	FActorSpawnParameters Params;
	Params.SpawnCollisionHandlingOverride = ESpawnActorCollisionHandlingMethod::AlwaysSpawn;
	const FVector From = FVector(GS->ExtractLocation) + FVector(-6000.f, 0.f, 4000.f);
	if (ADVGunship* Raven = GetWorld()->SpawnActor<ADVGunship>(ADVGunship::StaticClass(), From, FRotator::ZeroRotator, Params))
	{
		Raven->SetScriptedFlight(true);
		ExtractRaven = Raven;
	}
}

void ADVGameMode::SpawnWave(int32 Count)
{
	ADVGameState* GS = GetDVGameState();
	UNavigationSystemV1* Nav = UNavigationSystemV1::GetCurrent(GetWorld());
	const FVector Target = GS->ObjectiveLocation;
	int32 Spawned = 0;
	const float Base = FMath::FRandRange(0.f, 360.f);
	for (int32 i = 0; i < Count * 3 && Spawned < Count; ++i)
	{
		const FVector Dir = FRotator(0.f, Base + FMath::FRandRange(-50.f, 50.f), 0.f).Vector();
		FVector Loc = Target + Dir * FMath::FRandRange(3500.f, 5000.f);
		FNavLocation OnNav;
		if (!Nav || !Nav->ProjectPointToNavigation(Loc, OnNav, FVector(1200.f, 1200.f, 3000.f)))
		{
			continue;
		}
		Loc = OnNav.Location + FVector(0.f, 0.f, 100.f);
		const FTransform SpawnTransform((Target - Loc).Rotation(), Loc);
		ADVSoldierCharacter* Frame = GetWorld()->SpawnActorDeferred<ADVSoldierCharacter>(ADVSoldierCharacter::StaticClass(), SpawnTransform,
			nullptr, nullptr, ESpawnActorCollisionHandlingMethod::AdjustIfPossibleButAlwaysSpawn);
		if (!Frame)
		{
			continue;
		}
		Frame->TeamId = 2;
		Frame->SetAlerted(true);	// counter-attacks know exactly where you are
		Frame->FinishSpawning(SpawnTransform);
		if (!Frame->GetController())
		{
			Frame->SpawnDefaultController();
		}
		if (ADVSquadAIController* AI = Cast<ADVSquadAIController>(Frame->GetController()))
		{
			FDVSquadOrderData Order;
			Order.Order = EDVSquadOrder::MoveTo;
			Order.Location = Target;
			AI->ReceiveOrder(Order);
		}
		++Spawned;
	}
	GS->EnemiesTotal += Spawned;
	GS->EnemiesRemaining += Spawned;
}

void ADVGameMode::TickStage()
{
	ADVGameState* GS = GetDVGameState();
	if (!GS || bMissionEnded)
	{
		GetWorldTimerManager().ClearTimer(StageTimer);
		return;
	}
	const double Now = GetWorld()->GetTimeSeconds();
	switch (GS->Stage)
	{
	case EDVMissionStage::Sabotage:
		if (AnyPlayerNear(GS->ObjectiveLocation, 450.f))
		{
			GS->StageProgress = FMath::Min(1.f, GS->StageProgress + 0.25f / PlantSeconds);
			GS->MulticastSound(TEXT("SW_PlantBeep"), GS->ObjectiveLocation, 0.8f, 0);
			if (GS->StageProgress >= 1.f)
			{
				if (bScriptedObjectives && !SecondObjective.IsNearlyZero())
				{
					StartCapture();
				}
				else
				{
					StartDefend();
				}
			}
		}
		break;
	case EDVMissionStage::Capture:
		if (AnyPlayerNear(GS->ObjectiveLocation, 500.f))
		{
			GS->StageProgress = FMath::Min(1.f, GS->StageProgress + 0.25f / 5.f);
			GS->MulticastSound(TEXT("SW_PlantBeep"), GS->ObjectiveLocation, 0.6f, 0);
			if (GS->StageProgress >= 1.f)
			{
				StartDefend();
			}
		}
		break;
	case EDVMissionStage::Defend:
	{
		const float Elapsed = Now - StageStartTime;
		GS->StageProgress = FMath::Clamp(Elapsed / HoldSeconds, 0.f, 1.f);
		// Counter-attacks: one right away, a heavier one halfway through.
		if (WavesSpawned == 0 && Elapsed > 3.f)
		{
			SpawnWave(3);
			++WavesSpawned;
		}
		else if (WavesSpawned == 1 && Elapsed > HoldSeconds * 0.45f)
		{
			SpawnWave(4);
			++WavesSpawned;
			Radio(TEXT("Gny. Sgt. Halloran"), TEXT("Second wave! Make every round count!"));
		}
		if (Now >= GS->StageEndTime)
		{
			StartExtract();
		}
		break;
	}
	case EDVMissionStage::Extract:
	{
		const float T = FMath::Clamp((Now - StageStartTime) / RavenInboundSeconds, 0.f, 1.f);
		GS->StageProgress = T;
		if (ADVGunship* Raven = ExtractRaven.Get())
		{
			// Swoop in and settle into a low hover over the pad.
			const FVector Pad = FVector(GS->ExtractLocation) + FVector(0.f, 0.f, 260.f);
			const FVector From = FVector(GS->ExtractLocation) + FVector(-6000.f, 0.f, 4000.f);
			const float E = 1.f - FMath::Pow(1.f - T, 3.f);
			Raven->SetActorLocationAndRotation(FMath::Lerp(From, Pad, E), FRotator(-8.f * (1.f - T), 0.f, 0.f));
		}
		if (T >= 1.f && AnyPlayerNear(GS->ExtractLocation, 900.f))
		{
			Radio(TEXT("Raven Two-One"), TEXT("Everybody's aboard. Dust off!"));
			EndMission(true);
		}
		break;
	}
	default:
		break;
	}
}

void ADVGameMode::SpawnBulwarks()
{
	const FString Map = GetWorld()->GetMapName();
	if (Map.Contains(TEXT("Kestrel")) || Map.Contains(TEXT("BootCamp")))
	{
		return;
	}
	// One Bulwark anchors the enemy's centre of mass; big garrisons get a second on their flank.
	TArray<ADVSoldierCharacter*> Hostiles;
	FVector Centre = FVector::ZeroVector;
	for (TActorIterator<ADVSoldierCharacter> It(GetWorld()); It; ++It)
	{
		if (It->TeamId != PlayerTeamId && !It->IsA<ADVBulwark>())
		{
			Hostiles.Add(*It);
			Centre += It->GetActorLocation();
		}
	}
	if (Hostiles.Num() < 3)
	{
		return;
	}
	Centre /= Hostiles.Num();
	Hostiles.Sort([&Centre](const ADVSoldierCharacter& A, const ADVSoldierCharacter& B)
	{
		return FVector::DistSquared(A.GetActorLocation(), Centre) < FVector::DistSquared(B.GetActorLocation(), Centre);
	});
	const int32 Count = Hostiles.Num() >= 10 ? 2 : 1;
	UNavigationSystemV1* Nav = UNavigationSystemV1::GetCurrent(GetWorld());
	for (int32 i = 0; i < Count; ++i)
	{
		const ADVSoldierCharacter* Anchor = Hostiles[i == 0 ? 0 : Hostiles.Num() / 2];
		FVector Loc = Anchor->GetActorLocation() + Anchor->GetActorRotation().RotateVector(FVector(420.f, i == 0 ? 160.f : -160.f, 0.f));	// out in front, where it can be seen coming
		FNavLocation OnNav;
		if (Nav && Nav->ProjectPointToNavigation(Loc, OnNav, FVector(300.f, 300.f, 120.f)))
		{
			Loc = OnNav.Location;
		}
		FActorSpawnParameters Params;
		Params.SpawnCollisionHandlingOverride = ESpawnActorCollisionHandlingMethod::AdjustIfPossibleButAlwaysSpawn;
		ADVBulwark* Heavy = GetWorld()->SpawnActor<ADVBulwark>(ADVBulwark::StaticClass(), Loc + FVector(0.f, 0.f, 140.f), Anchor->GetActorRotation(), Params);
		UE_LOG(LogTemp, Log, TEXT("Bulwark spawned: %s at %s"), Heavy ? *Heavy->GetName() : TEXT("FAILED"), *Loc.ToString());
	}
}

bool ADVGameMode::CanCallIn(APlayerController* Caller, const FVector& Target, float ReadyTime) const
{
	const ADVGameState* GS = GetDVGameState();
	const APawn* CallerPawn = Caller ? Caller->GetPawn() : nullptr;
	return GS && !bMissionEnded && !bIsHub && CallerPawn && GetWorld()->GetTimeSeconds() >= ReadyTime
		&& FVector::Dist(CallerPawn->GetActorLocation(), Target) <= 20000.f;	// designator range (also guards against spoofed targets)
}

void ADVGameMode::RequestSupplyDrop(APlayerController* Caller, const FVector& Target)
{
	ADVGameState* GS = GetDVGameState();
	if (!GS || !CanCallIn(Caller, Target, GS->SupplyReadyTime))
	{
		return;
	}
	const ADVSoldierCharacter* Commander = Cast<ADVSoldierCharacter>(Caller->GetPawn());
	const float Favour = Commander && Commander->GetCommanderLevel() >= DVPerks::KestrelFavour ? 0.75f : 1.f;
	GS->SupplyReadyTime = GetWorld()->GetTimeSeconds() + SupplyCooldown * Favour;
	FActorSpawnParameters Params;
	Params.SpawnCollisionHandlingOverride = ESpawnActorCollisionHandlingMethod::AlwaysSpawn;
	if (ADVSupplyPod* Pod = GetWorld()->SpawnActor<ADVSupplyPod>(ADVSupplyPod::StaticClass(), Target + FVector(0.f, 0.f, 9000.f), FRotator::ZeroRotator, Params))
	{
		Pod->Launch(Target);
	}
	Radio(TEXT("Deck Chief Ruiz"), TEXT("Supply pod away! Ammo, med-gel and plates. Don't stand under it."));
}

void ADVGameMode::RequestStrafeRun(APlayerController* Caller, const FVector& Target)
{
	ADVGameState* GS = GetDVGameState();
	if (!GS || !CanCallIn(Caller, Target, GS->StrafeReadyTime))
	{
		return;
	}
	const ADVSoldierCharacter* Commander = Cast<ADVSoldierCharacter>(Caller->GetPawn());
	const float Favour = Commander && Commander->GetCommanderLevel() >= DVPerks::KestrelFavour ? 0.75f : 1.f;
	GS->StrafeReadyTime = GetWorld()->GetTimeSeconds() + StrafeCooldown * Favour;
	APawn* CallerPawn = Caller->GetPawn();
	ADVSoldierCharacter* Shooter = Cast<ADVSoldierCharacter>(CallerPawn);
	if (!Shooter)
	{
		if (const UDVSeatComponent* Seat = CallerPawn->FindComponentByClass<UDVSeatComponent>())
		{
			Shooter = Seat->Driver;
		}
	}
	// Run in along the caller's line of sight so the fire walks away from friendlies.
	FVector Dir = Target - CallerPawn->GetActorLocation();
	Dir.Z = 0.f;
	if (ADVStrafeRun* Run = GetWorld()->SpawnActor<ADVStrafeRun>(ADVStrafeRun::StaticClass(), Target, FRotator::ZeroRotator))
	{
		Run->Begin(Shooter, Target, Dir.GetSafeNormal());
	}
	Radio(TEXT("Raven Two-One"), TEXT("Two-One rolling in hot on your mark. Heads down!"));
}

ADVGameState* ADVGameMode::GetDVGameState() const
{
	return GetGameState<ADVGameState>();
}

bool ADVGameMode::AnySquadmateAlive() const
{
	for (const TWeakObjectPtr<ADVSoldierCharacter>& Weak : DeployedSquad)
	{
		if (Weak.IsValid() && !Weak->IsDead())
		{
			return true;
		}
	}
	return false;
}

void ADVGameMode::RequestRedeploy()
{
	if (bMissionEnded)
	{
		GetWorld()->ServerTravel(TEXT("?Restart"), /*bAbsolute*/ false);	// co-op clients come along
	}
}

void ADVGameMode::HandleStartingNewPlayer_Implementation(APlayerController* NewPlayer)
{
	// Co-op: later players take over a named squadmate instead of spawning a new body.
	if (bCoopPlayersTakeOverSquadmates && SquadLeader.IsValid() && NewPlayer != LeaderController.Get())
	{
		if (ADVSoldierCharacter* Free = FindFreeSquadmate())
		{
			AController* OldAI = Free->GetController();
			NewPlayer->Possess(Free);
			if (OldAI)
			{
				OldAI->Destroy();
			}
			UE_LOG(LogDV, Log, TEXT("%s takes over %s"), *GetNameSafe(NewPlayer), *Free->GetSoldierName());
			return;
		}
	}

	Super::HandleStartingNewPlayer_Implementation(NewPlayer);

	if (!SquadLeader.IsValid())
	{
		if (ADVSoldierCharacter* Leader = Cast<ADVSoldierCharacter>(NewPlayer->GetPawn()))
		{
			SquadLeader = Leader;
			LeaderController = NewPlayer;
			SpawnSquadFor(Leader);
		}
	}
}

void ADVGameMode::SpawnSquadFor(ADVSoldierCharacter* Leader)
{
	UDVRosterSubsystem* Roster = GetRoster();
	if (!Leader || !Roster || !SquadmateClass)
	{
		return;
	}

	// Losses from an abandoned mission still count, so top the roster up before choosing who deploys.
	Roster->Reinforce(SquadSize);
	const TArray<FGuid> Picked = Roster->SelectSquad(SquadSize);
	UNavigationSystemV1* Nav = UNavigationSystemV1::GetCurrent(GetWorld());

	for (int32 i = 0; i < Picked.Num(); ++i)
	{
		FDVSoldierRecord Record;
		if (!Roster->GetSoldier(Picked[i], Record))
		{
			continue;
		}

		FVector Location = Leader->GetActorLocation() + Leader->GetActorRotation().RotateVector(FVector(-200.f - 150.f * i, (i % 2 ? 200.f : -200.f), 0.f));
		FNavLocation NavLoc;
		if (Nav && Nav->ProjectPointToNavigation(Location, NavLoc, FVector(300.f, 300.f, 300.f)))
		{
			Location = NavLoc.Location + FVector(0.f, 0.f, 100.f);
		}

		const FTransform SpawnTransform(Leader->GetActorRotation(), Location);
		ADVSoldierCharacter* Mate = GetWorld()->SpawnActorDeferred<ADVSoldierCharacter>(SquadmateClass, SpawnTransform,
			nullptr, nullptr, ESpawnActorCollisionHandlingMethod::AdjustIfPossibleButAlwaysSpawn);
		if (!Mate)
		{
			continue;
		}
		Mate->TeamId = Leader->TeamId;
		Mate->FinishSpawning(SpawnTransform);
		if (!Mate->GetController())
		{
			Mate->SpawnDefaultController();
		}
		Mate->ApplyRosterRecord(Record);

		if (ADVSquadAIController* AI = Cast<ADVSquadAIController>(Mate->GetController()))
		{
			AI->SetLeader(Leader, i);
		}
		Leader->GetCommandComponent()->RegisterSquadMember(Mate);
		DeployedSquad.Add(Mate);
		DeployedIds.Add(Record.Id);

		UE_LOG(LogDV, Log, TEXT("Deployed %s"), *Mate->GetSoldierName());
	}
}

ADVSoldierCharacter* ADVGameMode::FindFreeSquadmate() const
{
	for (const TWeakObjectPtr<ADVSoldierCharacter>& Weak : DeployedSquad)
	{
		ADVSoldierCharacter* Mate = Weak.Get();
		if (Mate && !Mate->IsDead() && Cast<ADVSquadAIController>(Mate->GetController()))
		{
			return Mate;
		}
	}
	return nullptr;
}

void ADVGameMode::NotifySoldierKilled(ADVSoldierCharacter* Victim, ADVSoldierCharacter* Killer, AController* KillerController)
{
	if (!Victim)
	{
		return;
	}

	UDVRosterSubsystem* Roster = GetRoster();
	if (Roster && !bMissionEnded)
	{
		if (Victim->GetRosterId().IsValid())
		{
			const FString Cause = Killer ? FString::Printf(TEXT("Killed in action by %s"),
				Killer->GetSoldierName().IsEmpty() ? TEXT("enemy fire") : *Killer->GetSoldierName()) : TEXT("Killed in action");
			Roster->ReportKIA(Victim->GetRosterId(), Cause, MissionName);
		}
		if (Killer && Killer->GetRosterId().IsValid())
		{
			Roster->ReportKill(Killer->GetRosterId());
		}
	}

	if (bMissionEnded)
	{
		return;
	}

	const bool bFriendlyLoss = Victim->TeamId == PlayerTeamId;
	if (ADVGameState* GS = GetDVGameState())
	{
		const FString VictimName = Victim->GetSoldierName().IsEmpty() ? (bFriendlyLoss ? TEXT("You") : TEXT("Hearthbound trooper")) : Victim->GetSoldierName();
		const FString KillerName = !Killer ? TEXT("") : Killer->IsPlayerControlled() ? TEXT("You")
			: Killer->GetSoldierName().IsEmpty() ? TEXT("War-frame") : Killer->GetSoldierName();
		GS->MulticastKillFeed(KillerName, VictimName, bFriendlyLoss);

		if (bFriendlyLoss && Victim->GetRosterId().IsValid())
		{
			Radio(TEXT("Gny. Sgt. Halloran"), FString::Printf(TEXT("We lost %s! Keep moving, Delta!"), *Victim->GetSoldierName()));
		}
		if (!bFriendlyLoss)
		{
			++HostileKills;
			if (HostileKills == 1)
			{
				Radio(TEXT("Gny. Sgt. Halloran"), TEXT("Scratch one tin can! They bleed oil, people. Keep it up."));
			}
			else if (GS->EnemiesTotal > 3 && GS->EnemiesRemaining - 1 == GS->EnemiesTotal / 2 && !bIsTrainingMap)
			{
				Radio(TEXT("CINDER"), TEXT("YOUR LOSSES ARE ACCEPTABLE. MINE ARE IRRELEVANT."));
			}
			GS->EnemiesRemaining = FMath::Max(0, GS->EnemiesRemaining - 1);
			if (GS->EnemiesRemaining == 0 && GS->bMultiStage)
			{
				if (GS->Stage == EDVMissionStage::Clear)
				{
					StartSabotage();
				}
			}
			else if (GS->EnemiesRemaining == 0)
			{
				// Let the last kill land before the after-action screen.
				FTimerHandle Handle;
				GetWorldTimerManager().SetTimer(Handle, FTimerDelegate::CreateUObject(this, &ADVGameMode::EndMission, true), 2.f, false);
				return;
			}
		}
	}

	if (APlayerController* PC = Cast<APlayerController>(Victim->GetController()))
	{
		// The leader reinforces onto the field as long as someone from the squad is still fighting.
		if (!AnySquadmateAlive())
		{
			EndMission(false);
			return;
		}
		FTimerHandle Handle;
		GetWorldTimerManager().SetTimer(Handle, FTimerDelegate::CreateUObject(this, &ADVGameMode::RespawnPlayer,
			TWeakObjectPtr<APlayerController>(PC)), PlayerRespawnDelay, false);
	}
	else if (bFriendlyLoss && !AnySquadmateAlive())
	{
		const ADVSoldierCharacter* Leader = SquadLeader.Get();
		if (!Leader || Leader->IsDead())
		{
			EndMission(false);
		}
	}
}

void ADVGameMode::NotifySoldierDowned(ADVSoldierCharacter* Soldier)
{
	if (bMissionEnded || !Soldier)
	{
		return;
	}
	const FString Name = Soldier->IsPlayerControlled() ? FString(TEXT("Commander")) : Soldier->GetSoldierName();
	Radio(TEXT("Gny. Sgt. Halloran"), FString::Printf(TEXT("%s is down! Somebody get to them!"), *Name));
	if (ADVGameState* GS = GetDVGameState())
	{
		GS->MulticastSound(TEXT("SW_RadioSquelch"), Soldier->GetActorLocation(), 1.f, 0);
	}
}

