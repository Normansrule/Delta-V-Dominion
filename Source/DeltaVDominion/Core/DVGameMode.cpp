ADVGameMode::ADVGameMode()
{
	DefaultPawnClass = ADVSoldierCharacter::StaticClass();
	PlayerControllerClass = ADVPlayerController::StaticClass();
	GameStateClass = ADVGameState::StaticClass();
	HUDClass = ADVHUD::StaticClass();
	SquadmateClass = ADVSoldierCharacter::StaticClass();

	SuccessReward.Manpower = 4;
	SuccessReward.Materiel = 40;
	SuccessReward.Fuel = 25;
}

UDVRosterSubsystem* ADVGameMode::GetRoster() const
{
	const UGameInstance* GI = GetGameInstance();
	return GI ? GI->GetSubsystem<UDVRosterSubsystem>() : nullptr;
}

void ADVGameMode::StartPlay()
{
	// Levels may ship without baked nav data (grey-box maps are generated by script), so make sure
	// the navmesh is built from the level's geometry before any AI asks for a path.
	if (UNavigationSystemV1* Nav = UNavigationSystemV1::GetCurrent(GetWorld()))
	{
		Nav->Build();
	}
	Super::StartPlay();
	SpawnBulwarks();

	// Objective: neutralise every hostile placed in the level.
	if (ADVGameState* GS = GetDVGameState())
	{
		int32 Hostiles = 0;
		for (TActorIterator<ADVSoldierCharacter> It(GetWorld()); It; ++It)
		{
			Hostiles += It->TeamId != PlayerTeamId ? 1 : 0;
		}
		GS->EnemiesTotal = Hostiles;
		GS->EnemiesRemaining = Hostiles;
		GS->MissionStartTime = GetWorld()->GetTimeSeconds();
		GS->OrbitalReadyTime = GS->MissionStartTime + 12.f;
		GS->SupplyReadyTime = GS->MissionStartTime + 15.f;
		GS->StrafeReadyTime = GS->MissionStartTime + 20.f;
	}
	SetupMissionForMap();
}

