void ADVGameMode::RespawnPlayer(TWeakObjectPtr<APlayerController> WeakPC)
{
	APlayerController* PC = WeakPC.Get();
	if (!PC || bMissionEnded)
	{
		return;
	}
	PC->UnPossess();
	RestartPlayer(PC);

	if (PC == LeaderController.Get())
	{
		if (ADVSoldierCharacter* NewLeader = Cast<ADVSoldierCharacter>(PC->GetPawn()))
		{
			RelinkSquadTo(NewLeader);
		}
	}
}

void ADVGameMode::RelinkSquadTo(ADVSoldierCharacter* NewLeader)
{
	SquadLeader = NewLeader;
	int32 Slot = 0;
	for (const TWeakObjectPtr<ADVSoldierCharacter>& Weak : DeployedSquad)
	{
		ADVSoldierCharacter* Mate = Weak.Get();
		if (!Mate || Mate->IsDead())
		{
			continue;
		}
		NewLeader->GetCommandComponent()->RegisterSquadMember(Mate);
		if (ADVSquadAIController* AI = Cast<ADVSquadAIController>(Mate->GetController()))
		{
			AI->SetLeader(NewLeader, Slot);
		}
		++Slot;
	}
}

void ADVGameMode::EndMission(bool bSuccess)
{
	UDVRosterSubsystem* Roster = GetRoster();
	if (bMissionEnded || !Roster)
	{
		return;
	}
	bMissionEnded = true;

	FDVMissionReport Report;
	Report.MissionName = MissionName;
	Report.bSuccess = bSuccess;
	if (bSuccess)
	{
		Report.Reward = SuccessReward;
	}

	for (const TWeakObjectPtr<ADVSoldierCharacter>& Weak : DeployedSquad)
	{
		const ADVSoldierCharacter* Mate = Weak.Get();
		if (!Mate || Mate->IsDead())
		{
			continue;
		}
		Report.Survivors.Add(Mate->GetRosterId());
		if (const UDVAttributeSet* Attr = Mate->GetAttributeSet(); Attr && Attr->DamageTakenFraction >= WoundedThreshold)
		{
			Report.Wounded.Add(Mate->GetRosterId());
		}
	}

	TMap<FGuid, EDVRank> RanksBefore;
	for (const FGuid& Id : DeployedIds)
	{
		FDVSoldierRecord Before;
		if (Roster->GetSoldier(Id, Before))
		{
			RanksBefore.Add(Id, Before.Rank);
		}
	}

	Roster->CompleteMission(Report);

	Radio(TEXT("Capt. Vance (Kestrel)"), bSuccess
		? (bIsTrainingMap ? FString(TEXT("Range is clear. Not bad, Delta. Not good either. Again tomorrow.")) : FString(TEXT("Relay's dark. Good work, Delta. Bringing you home.")))
		: FString(TEXT("Delta's gone quiet... Kestrel to any Delta unit, respond. Any Delta unit...")));

	if (ADVGameState* GS = GetDVGameState())
	{
		GS->Phase = bSuccess ? EDVMissionPhase::Success : EDVMissionPhase::Failure;
		GS->MissionEndTime = GetWorld()->GetTimeSeconds();
		GS->AfterAction.Reset();
		for (const FGuid& Id : DeployedIds)
		{
			FDVSoldierRecord After;
			if (!Roster->GetSoldier(Id, After))
			{
				continue;
			}
			FDVAfterActionLine& Line = GS->AfterAction.AddDefaulted_GetRef();
			Line.Name = After.GetDisplayName();
			Line.Rank = UDVRosterSubsystem::RankToString(After.Rank);
			Line.Kills = After.Kills;
			Line.bKIA = After.Status == EDVSoldierStatus::KIA;
			Line.bWounded = After.Status == EDVSoldierStatus::Wounded;
			Line.bPromoted = RanksBefore.Contains(Id) && After.Rank > RanksBefore[Id];
		}
	}
	UE_LOG(LogDV, Log, TEXT("Mission %s ended (%s): %d survivors, %d wounded"), *MissionName,
		bSuccess ? TEXT("success") : TEXT("failure"), Report.Survivors.Num(), Report.Wounded.Num());
}
